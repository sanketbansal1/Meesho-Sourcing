export function makeT(lang: Lang) {
  return (key: keyof typeof D | string): string => {
    const entry = D[key as string];
    if (!entry) return key as string;
    return lang === "hi" ? entry[1] : entry[0];
  };
}

export type TFunc = ReturnType<typeof makeT>;
